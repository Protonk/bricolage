"""Deterministic current collection totals, derived only from active manifests."""
import json
import os
from pathlib import Path
from urllib.parse import quote

from fixture_layout import FIXTURES, discover, check_layout, require


def render(fixtures=FIXTURES, leaves=None):
    fixtures = Path(fixtures)
    leaves = discover(fixtures) if leaves is None else sorted(leaves)
    rows, all_hashes, count = [], set(), 0
    for leaf in leaves:
        check_layout(leaf, assets=False)
        manifest = json.loads((leaf / 'manifest.json').read_text())
        hashes = {r['byte_sha256'] for r in manifest['images']}
        relative = leaf.relative_to(fixtures).as_posix()
        rows.append(f'| [{relative}]({quote(relative)}/README.md) | {len(manifest["images"]):,} | {len(hashes):,} |')
        count += len(manifest['images'])
        all_hashes.update(hashes)
    return '\n'.join([
        '# Collection totals', '',
        '<!-- Generated by Fixtures/collection totals. Do not edit by hand. -->', '',
        f'**{count:,} active inputs · {len(leaves):,} collections · {len(all_hashes):,} distinct byte hashes**', '',
        'These are manifest totals, not a check of local media availability. Historical',
        'acquisition counts and targets remain in each collection’s provenance.', '',
        '| Collection | Active inputs | Distinct byte hashes |',
        '|---|---:|---:|', *rows, '',
        'Regenerate with `Fixtures/collection totals`; verify with',
        '`Fixtures/collection totals --check`.', '',
    ])


def generated_files(fixtures=FIXTURES):
    """One central table plus marked totals in each leaf's guide."""
    leaves = discover(fixtures)
    files = {fixtures / 'COLLECTIONS.md': render(fixtures, leaves)}
    for leaf in leaves:
        path = leaf / 'README.md'
        text = path.read_text()
        start, end = '<!-- collection-totals:start -->', '<!-- collection-totals:end -->'
        require(text.count(start) == text.count(end) == 1, f'Missing collection-total markers: {path}')
        count = len(json.loads((leaf / 'manifest.json').read_text())['images'])
        link = Path(os.path.relpath(fixtures / 'COLLECTIONS.md', leaf)).as_posix()
        body = f'\nThe manifest lists **{count:,} active inputs**. [All collection totals]({link}).\n'
        left, rest = text.split(start)
        _, right = rest.split(end)
        files[path] = left + start + body + end + right
    return files


def update(fixtures=FIXTURES, *, check=False):
    files = generated_files(fixtures)
    changed = [path for path, content in files.items() if not path.exists() or path.read_text() != content]
    if check:
        require(not changed, 'Stale collection totals; run Fixtures/collection totals: ' + ', '.join(str(p) for p in changed))
    else:
        from fixture_removal import atomic_write
        for path in changed:
            atomic_write(path, files[path].encode())
    return dict(status='current' if check else 'generated', changed=[str(p) for p in changed])
