#!/usr/bin/env python3
"""Copy this specimen's catalogs and construct its pinned PNGs at a new leaf path."""
import argparse
import hashlib
from pathlib import Path
import shutil
import struct
import tempfile
import zlib

LEAF = Path(__file__).resolve().parents[1]
PATTERN = (
    "................",
    ".........#......",
    ".........###....",
    "..#o#o#######...",
    "..#o#o#########.",
    "..#o#o#########.",
    "..#o#o#######...",
    ".........###....",
    ".........#......",
    "................",
)
COLORS = {".": bytes((244, 236, 210)), "#": bytes((19, 85, 93)), "o": bytes((240, 165, 54))}
SCALE = 6


def chunk(tag, data):
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))


def png(pattern, text=None):
    width, height = len(pattern[0]) * SCALE, len(pattern) * SCALE
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    # Each row has PNG filter 0. One stored DEFLATE block fixes the bytes across encoders.
    raw = b"".join((b"\x00" + b"".join(COLORS[c] * SCALE for c in row)) * SCALE for row in pattern)
    block = b"\x01" + struct.pack("<HH", len(raw), len(raw) ^ 0xffff) + raw
    compressed = b"\x78\x01" + block + struct.pack(">I", zlib.adler32(raw))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + (chunk(b"tEXt", text) if text else b"") + chunk(b"IDAT", compressed) + chunk(b"IEND", b""))


def materialize(destination):
    destination = destination.parent.resolve() / destination.name
    if destination.exists() or destination.is_symlink():
        raise FileExistsError(f"Destination already exists: {destination}")
    if destination.is_relative_to(LEAF):
        raise ValueError("Choose a new destination outside the recipe directory")
    a = png(PATTERN)
    media = {
        "sources/arrow.png": a,
        "images/01.png": a,
        "images/02.png": a,
        "images/03.png": png([row[::-1] for row in PATTERN]),
        "images/04.png": png(PATTERN, b"Description\x00Same arrow, second encoding"),
    }
    pinned = {path: digest for digest, path in
              (line.split("  ", 1) for line in (LEAF / "SHA256SUMS.txt").read_text().splitlines())}
    if set(pinned) != set(media):
        raise ValueError("Recipe paths differ from SHA256SUMS.txt")
    for name, data in media.items():
        if hashlib.sha256(data).hexdigest() != pinned[name]:
            raise ValueError("Generated bytes differ from the pinned hash for " + name)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=destination.parent, prefix=".build-arrow-") as staging:
        staged = Path(staging) / "leaf"
        shutil.copytree(LEAF, staged, ignore=shutil.ignore_patterns(
            "images", "sources", "previews", "__pycache__", ".DS_Store"))
        for directory in ("images", "sources", "previews"):
            (staged / directory).mkdir()
        for name, data in media.items():
            (staged / name).write_bytes(data)
        # Reserve the name before rename so concurrent builders cannot replace a destination.
        destination.mkdir()
        try:
            staged.rename(destination)
        except OSError:
            destination.rmdir()
            raise
    return destination


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("destination", type=Path, help="New leaf directory in the disposable archive")
    args = parser.parse_args()
    try:
        print(materialize(args.destination))
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + "\n")
