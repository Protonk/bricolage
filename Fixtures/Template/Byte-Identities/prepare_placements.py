"""Make two disposable archives for the placement experiment. Print their parent directory."""
import csv
import hashlib
import json
from pathlib import Path
import shutil
import sys
import tempfile

HERE = Path(__file__).resolve().parent
FIXTURES = HERE.parents[1]
sys.path.insert(0, str(FIXTURES / "tools"))
from fixture_layout import check_layout
from new_fixture import create
from test_collection import png

sys.path.insert(0, str(HERE / "leaf/tools"))
from materialize import materialize


def write_row(catalog, row):
    with catalog.open(newline="") as stream:
        fields = next(csv.reader(stream))
    with catalog.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerow(row)


def make_host(fixtures):
    host = fixtures / "Relationships/Host"
    create(host, "bricolage-host01-v1", "derivatives", fixtures)
    data = png(42)
    digest = hashlib.sha256(data).hexdigest()
    name = "images/host.png"
    image = dict(file=name, batch="batch-1", family_id="host", scene_id="", parents="host",
                 transformation="source", relation_kind="identity", origin_count=1,
                 width=1, height=1, exif_orientation=1, format="PNG", byte_sha256=digest,
                 pixels_rgb_sha256=hashlib.sha256(bytes([42, 38, 34])).hexdigest())
    source = dict(family_id="host", source_filename="host.png", subject="Single color pixel",
                  credit_status="Bricolage test generator", source_sha256=digest, width=1,
                  height=1, exif_orientation=1, preprocessing="Constructed from seed 42",
                  original_path="test_collection.png")
    manifest = dict(schema_version=1, kind="derivatives", fixture_id="bricolage-host01-v1",
                    description="One-pixel placement control.", images=[image])
    (host / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    write_row(host / "manifest.csv", image)
    write_row(host / "sources.csv", source)
    paths = (name, "sources/host.png")
    for path in paths:
        (host / path).write_bytes(data)
    (host / "SHA256SUMS.txt").write_text("".join(f"{digest}  {path}\n" for path in paths))
    for batch in ("batch-1", "smoke", "medium"):
        (host / f"batches/{batch}.txt").write_text(name + "\n")
    (host / "README.md").write_text(
        "# Placement host\n\nOne RGB pixel from `png(42)` in `Fixtures/tools/test_collection.py`.\n"
        "\n<!-- collection-totals:start -->\n<!-- collection-totals:end -->\n")
    (host / "SOURCES.md").write_text("Original control pixel generated by Bricolage.\n")
    (host / "provenance/README.md").write_text("Seed 42 produces the input and source PNG.\n")
    check_layout(host)
    return host


def main():
    root = Path(tempfile.mkdtemp(dir=FIXTURES / "output", prefix="byte-placements-"))
    sibling = root / "sibling/Fixtures"
    nested = root / "nested/Fixtures"
    for fixtures in (sibling, nested):
        (fixtures / "Heaps").mkdir(parents=True)
    host = make_host(sibling)
    nested_host = nested / "Relationships/Host"
    shutil.copytree(host, nested_host)
    specimen = materialize(sibling / "Relationships/Groups/Level/Example")
    shutil.copytree(specimen, nested_host / "tools/example")
    print(root)


if __name__ == "__main__":
    main()
